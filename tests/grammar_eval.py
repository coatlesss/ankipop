def score(name, labeled, lookup):
    tp = fp = fn = 0
    for sentence, expected in labeled.items():
        found = {p.name for p in find_grammar(sentence, lookup)}
        tp, fp, fn = tp + len(found & expected), fp + len(found - expected), fn + len(expected - found)
        if found != expected:
            print(f'{sentence}  missing: {sorted(expected - found)}  wrong: {sorted(found - expected)}')
    print(f'{name}, {len(labeled)} sentences: precision {tp / (tp + fp):.0%} ({fp} wrong), '
          f'recall {tp / (tp + fn):.0%} ({fn} missed)\n')


def main():
    known = {p.point.name for p in PHRASES} | {p.name for p in CONJUGATION_POINTS.values()}
    typos = {name for labeled in (LABELED, HELD_OUT, HELD_OUT_2) for expected in labeled.values() for name in expected} - known
    assert not typos, f'unknown grammar point names: {typos}'

    lookup = Lookup(MagicMock(), MagicMock())  # loads the real dictionary
    score('tuned on', LABELED, lookup)
    score('held out', HELD_OUT, lookup)
    score('held out, third batch', HELD_OUT_2, lookup)


if __name__ == '__main__':
    sys.exit(main())
