# meikipop/grammar_points.py
"""The grammar ankipop can explain. Explanations are written for this project.

CONJUGATION_POINTS maps the deconjugator's step names (see scripts/deconjugator.json) to grammar points, so conjugated
words are recognized the way the popup reads them (見てる is 〜ている, 捨てる is just a verb).
PHRASES are fixed multi-word patterns found with regexes. Each has an example sentence its regex must match
(checked in tests/test_grammar.py).
"""
from dataclasses import dataclass, field

TE = r'(?:て|(?<=[んい])(?<!なん)で)'  # te-form ending: で only after ん/い (読んで, 泳いで), so 出た and なんでも don't count


@dataclass(frozen=True)
class GrammarPoint:
    name: str
    level: str  # JLPT level, N5 (first year) to N1
    meaning: str


@dataclass(frozen=True)
class Phrase:
    pattern: str
    point: GrammarPoint
    example: str
    at_word_start: bool = False  # must start where a dictionary word starts (らしい, but not inside 新しい)
    hides: frozenset = field(default_factory=frozenset)  # conjugation steps this phrase explains better


def _p(name, level, meaning):
    return GrammarPoint(name, level, meaning)


